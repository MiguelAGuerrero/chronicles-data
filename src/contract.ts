// The contract the app reads (decision 0108 in the app repo): everything a client may rely on, generated from the
// pipeline's own code and committed in contract/, then served beside the archives by the Pages workflow.
//
//   npm run contract            writes contract/
//   npm run contract -- --check fails when contract/ differs from what the code says (the tests run this)
//
// - places.schema.json: the canonical shape (candidates, places, a pack's tile feature) and the class names.
// - manifest.schema.json: manifest.json, which the app reads to find a region's file and its blocks.
// - sources.json: each adapter's name, license, attribution, role and hosts (the app credits them; and no phone may
//   call these hosts, PP16).
// - example/: a small pack built from the test fixtures, and its manifest, for the app's tests to read.
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ADAPTERS } from './cli';
import { CLASS_NAMES, CONTRACT_VERSION } from './classes';
import { emptyRegistry } from './conflate';
import { partOf } from './adapters/wikidata';
import { createRawStore } from './rawStore';
import { run } from './runner';
import { jsonSchema } from './schema';

const ROOT = join(fileURLToPath(import.meta.url), '../..');
const FIX = join(ROOT, 'test/fixtures');

const MANIFEST_SCHEMA = {
  $schema: 'https://json-schema.org/draft/2020-12/schema',
  $comment: 'manifest.json as scripts/manifest.mjs writes it. Generated by `npm run contract`.',
  contractVersion: CONTRACT_VERSION,
  type: 'object',
  required: ['schema', 'regions'],
  properties: {
    schema: { const: 1 },
    regions: {
      type: 'array',
      items: {
        type: 'object',
        required: ['id', 'current', 'previous'],
        properties: {
          id: { type: 'string', pattern: '^[a-z0-9]+$' },
          current: { $ref: '#/$defs/file' },
          previous: { type: 'array', items: { $ref: '#/$defs/file' }, description: 'Older versions still served, newest first' },
        },
      },
    },
  },
  $defs: {
    file: {
      type: 'object',
      required: ['file', 'version', 'bounds'],
      properties: {
        file: { type: 'string', pattern: '^places-[a-z0-9]+-\\d{8}(?:\\.\\d+)?\\.pmtiles$', description: 'Beside the manifest, never a path' },
        version: { type: 'string' },
        bytes: { type: 'integer' },
        sha256: { type: 'string' },
        minzoom: { type: 'integer' },
        maxzoom: { type: 'integer' },
        bounds: { type: 'array', items: { type: 'number' }, minItems: 4, maxItems: 4, description: '[west, south, east, north]' },
        blocks: {
          type: 'object',
          description: 'PP11: a hash of the places in each z8 block; a client rebuilds an area only when its block changes',
          propertyNames: { pattern: '^8/\\d+/\\d+$' },
          additionalProperties: { type: 'string', pattern: '^[0-9a-f]{16}$' },
        },
      },
    },
  },
};

const json = (v: unknown) => `${JSON.stringify(v, null, 2)}\n`;

/** Every file of contract/, by path, as the code says it should be. */
export async function contractFiles(): Promise<Map<string, string | Buffer>> {
  const files = new Map<string, string | Buffer>();
  files.set('places.schema.json', json(jsonSchema()));
  files.set('manifest.schema.json', json(MANIFEST_SCHEMA));
  files.set('sources.json', json({
    contractVersion: CONTRACT_VERSION,
    classes: CLASS_NAMES,
    sources: ADAPTERS.map(({ declaration: d }) => ({ name: d.name, code: d.code, license: d.license, licenseFamily: d.licenseFamily, attribution: d.attribution, role: d.role, hosts: d.hosts })),
  }));

  // The example pack: the test fixtures through the whole pipeline, with IDs from a counter so it is the same each time.
  const store = createRawStore(mkdtempSync(join(tmpdir(), 'contract-raw-')));
  for (const cell of [[-76, 40, -74, 42], [-74, 40, -72, 42]] as [number, number, number, number][]) store.put('wikidata', '20261109', partOf(cell), readFileSync(join(FIX, partOf(cell)), 'utf8'), '2026-11-09T07:17:00.000Z');
  store.complete('wikidata', '20261109');
  let n = 0;
  const r = await run({
    adapters: ADAPTERS, region: 'example', area: [[-76, 40, -72, 42]], version: '20261109', store, registry: emptyRegistry(), edits: { remove: [], add: [] },
    fetch: false, http: async () => { throw new Error('the example asks nothing'); }, clock: { now: () => Date.parse('2026-11-09T07:17:00Z'), sleep: async () => {} },
    newId: () => `p_${(++n).toString(16).padStart(16, '0')}`,
  });
  const dir = mkdtempSync(join(tmpdir(), 'contract-example-'));
  for (const p of r.packs) {
    writeFileSync(join(dir, p.file), p.bytes);
    writeFileSync(join(dir, p.file.replace(/\.pmtiles$/, '.blocks.json')), `${JSON.stringify(p.blocks)}\n`);
    files.set(`example/${p.file}`, Buffer.from(p.bytes));
  }
  files.set('example/manifest.json', execFileSync(process.execPath, [join(ROOT, 'scripts/manifest.mjs'), dir], { encoding: 'utf8' }));
  return files;
}

async function main() {
  const files = await contractFiles();
  const check = process.argv.includes('--check');
  const stale: string[] = [];
  for (const [path, body] of files) {
    const target = join(ROOT, 'contract', path);
    if (check) {
      let now: Buffer | null = null;
      try {
        now = readFileSync(target);
      } catch {
        // missing
      }
      if (!now || !now.equals(Buffer.from(body))) stale.push(path);
    } else {
      mkdirSync(join(target, '..'), { recursive: true });
      writeFileSync(target, body);
    }
  }
  if (check && stale.length) {
    console.error(`contract/ is stale (run npm run contract): ${stale.join(', ')}`);
    process.exit(1);
  }
  if (!check) console.log(`wrote ${files.size} files to contract/`);
}

if (import.meta.url === `file://${process.argv[1]}`) main();
